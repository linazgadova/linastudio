/** Адрес картинки со значком. Тема светлая: у сайта нет тёмной. */
export function iksImage(site: string, lang: 'ru' | 'en') {
  return `https://yandex.ru/cycounter?${site}&theme=light&lang=${lang}`
}

/** Куда ведёт значок: страница сайта в Вебмастере. */
export function iksLink(site: string) {
  return `https://webmaster.yandex.ru/siteinfo/?site=${site}`
}
