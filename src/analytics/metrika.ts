import { CONSENT_KEY, METRIKA_ID } from '../data/analytics'

/**
 * ЗАГРУЗКА СЧЁТЧИКА
 *
 * Счётчик подключается только после того, как человек согласился.
 * Это не перестраховка: Метрика ставит куки и передаёт данные о
 * посещении третьей стороне, а такое в России требует уведомления
 * и согласия. Поэтому и порядок именно такой — сначала спросили,
 * потом загрузили, а не наоборот с возможностью «отписаться».
 *
 * Скрипт грузится один раз за жизнь страницы: повторный вызов
 * ничего не делает.
 */

type Ya = ((...args: unknown[]) => void) & { a?: unknown[]; l?: number }

declare global {
  interface Window {
    ym?: Ya
  }
}

let started = false

export function hasConsent(): boolean {
  try {
    return localStorage.getItem(CONSENT_KEY) === 'yes'
  } catch {
    // Приватный режим в некоторых браузерах запрещает хранилище.
    // Нет памяти — нет согласия: считать молчание согласием нельзя
    return false
  }
}

/**
 * Событие о том, что человек ответил.
 *
 * Счётчик — не единственное, что зависит от ответа: от него же
 * зависит значок качества сайта в подвале, потому что он тоже
 * картинка с чужого сервера, то есть тоже обращение к третьей
 * стороне. Хранилище о своих изменениях не сообщает, событие
 * storage приходит только в другие вкладки — поэтому своё.
 */
export const CONSENT_EVENT = 'zg:consent'

export function rememberConsent(agreed: boolean) {
  try {
    localStorage.setItem(CONSENT_KEY, agreed ? 'yes' : 'no')
  } catch {
    // Не запомнили — спросим в следующий раз. Это хуже для человека,
    // но честнее, чем считать, что он согласился
  }
  window.dispatchEvent(new CustomEvent(CONSENT_EVENT, { detail: agreed }))
}

export function startMetrika() {
  if (started || !METRIKA_ID || typeof window === 'undefined') return
  started = true

  /*
    Очередь до загрузки скрипта.

    Счётчик приезжает с чужого сервера и не мгновенно, а события за это
    время уже происходят. Заглушка складывает вызовы в массив, а
    настоящий скрипт, загрузившись, разбирает его и отправляет всё
    накопленное. Так первое посещение не теряется на медленной связи.
  */
  const stub: Ya = function (...args: unknown[]) {
    ;(stub.a = stub.a || []).push(args)
  }
  stub.l = Date.now()
  window.ym = window.ym || stub

  const s = document.createElement('script')
  s.async = true
  // Номер в адресе скрипта — так его отдают в самой Метрике: по нему
  // Яндекс подбирает нужную сборку счётчика ещё до её выполнения
  s.src = `https://mc.yandex.ru/metrika/tag.js?id=${METRIKA_ID}`
  document.head.appendChild(s)

  window.ym(METRIKA_ID, 'init', {
    // Страницы сайта приезжают уже с текстом, а не собираются
    // в браузере с нуля. Счётчику это нужно знать: иначе он считает
    // первый экран пустым и портит статистику по отказам
    ssr: true,
    // Карта скроллинга здесь ценнее всего: страница одна и длинная,
    // и главный вопрос — до какого блока вообще дочитывают
    clickmap: true,
    trackLinks: true,
    accurateTrackBounce: true,
    webvisor: true,
    // Адрес и источник задаются явно: счётчик подключается не сразу,
    // а после ответа про куки, и к этому моменту он бы уже мог
    // принять за источник перехода саму же страницу
    referrer: document.referrer,
    url: location.href,
  })

  /*
    Пиксель для браузеров без скриптов из кода Метрики сюда не
    перенесён намеренно. Он срабатывает сразу при разборе страницы,
    то есть до того, как человека о чём-либо спросили, — а весь смысл
    плашки в том, что до согласия не отправляется ничего.
  */
}

/**
 * Сообщить счётчику о переходе внутри сайта.
 *
 * Сайт не перезагружает страницу при переходе на проект, поэтому сам
 * счётчик такой переход не заметит: для него это по-прежнему тот же
 * визит на первый адрес. Без этого вызова вся статистика по страницам
 * проектов была бы пустой.
 */
export function trackPage(url: string, referrer: string) {
  if (!METRIKA_ID) return
  window.ym?.(METRIKA_ID, 'hit', url, { referer: referrer })
}
